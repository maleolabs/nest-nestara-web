<?php

namespace Tests\Unit\Support\Version;

use App\Support\Version\Exceptions\InvalidVersionFileException;
use App\Support\Version\Parsers\VersionParser;
use PHPUnit\Framework\TestCase;

final class VersionParserTest extends TestCase
{
    private string $tempFile;

    protected function setUp(): void
    {
        parent::setUp();

        $this->tempFile = (string) tempnam(sys_get_temp_dir(), 'version-test-');
    }

    protected function tearDown(): void
    {
        if (file_exists($this->tempFile)) {
            unlink($this->tempFile);
        }

        parent::tearDown();
    }

    public function test_parses_all_fields_from_version_file(): void
    {
        file_put_contents($this->tempFile, <<<'CONTENT'
            NAME=nestara-web
            PRODUCT_NAME=Nestara
            ORIGINAL_NAME=Nestara
            VERSION=1.0.0
            RELEASE=Genesis
            CODENAME=Genesis
            BUILD=1
            STATUS=alpha
            LICENSE=proprietary
            COPYRIGHT=MaleoLabs
            RELEASE_DATE=2026-08-22
            WEBSITE=https://maleolabs.com
            MINIMUM_PHP_VERSION=8.4
            CONTENT);

        $data = (new VersionParser)->parse($this->tempFile);

        $this->assertSame('nestara-web', $data['NAME']);
        $this->assertSame('Nestara', $data['PRODUCT_NAME']);
        $this->assertSame('Nestara', $data['ORIGINAL_NAME']);
        $this->assertSame('1.0.0', $data['VERSION']);
        $this->assertSame('Genesis', $data['RELEASE']);
        $this->assertSame('Genesis', $data['CODENAME']);
        $this->assertSame('1', $data['BUILD']);
        $this->assertSame('alpha', $data['STATUS']);
        $this->assertSame('proprietary', $data['LICENSE']);
        $this->assertSame('MaleoLabs', $data['COPYRIGHT']);
        $this->assertSame('2026-08-22', $data['RELEASE_DATE']);
        $this->assertSame('https://maleolabs.com', $data['WEBSITE']);
        $this->assertSame('8.4', $data['MINIMUM_PHP_VERSION']);
    }

    public function test_ignores_unknown_keys_blank_lines_and_comments(): void
    {
        file_put_contents($this->tempFile, <<<'CONTENT'
            # Generated by anvil project version generate

            PRODUCT_NAME=Nestara
            VERSION=1.0.0
            FRAMEWORK=laravel
            TIMESTAMP=2026-08-22T00:00:00+00:00
            DESCRIPTION=Sistem Informasi Perizinan Online
            CONTENT);

        $data = (new VersionParser)->parse($this->tempFile);

        $this->assertSame('Nestara', $data['PRODUCT_NAME']);
        $this->assertSame('1.0.0', $data['VERSION']);

        // Unknown keys are tolerated and kept in the map.
        $this->assertSame('laravel', $data['FRAMEWORK']);
        $this->assertSame('2026-08-22T00:00:00+00:00', $data['TIMESTAMP']);
        $this->assertSame('Sistem Informasi Perizinan Online', $data['DESCRIPTION']);
        $this->assertArrayNotHasKey('# Generated by anvil project version generate', $data);
        $this->assertCount(5, $data);
    }

    public function test_throws_when_file_is_missing(): void
    {
        $this->expectException(InvalidVersionFileException::class);

        (new VersionParser)->parse(sys_get_temp_dir().'/does-not-exist-'.uniqid());
    }
}
